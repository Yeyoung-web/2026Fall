import { test, expect } from '@playwright/test'
test('390px: 만남 생성, 새로고침 복원, 사진 fallback, 반응과 댓글', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/')
  await page.getByRole('button', { name: '새로운 만남 기록하기' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('만남 이름').fill('브라우저에서 검증한 하루')
  await dialog.getByLabel('장소명').fill('단골 떡볶이')
  await dialog.getByLabel('금액 (원)').fill('40000')
  await dialog.getByRole('button', { name: '우리의 만남 기록하기' }).click()
  await expect(page.getByRole('heading', { name: '브라우저에서 검증한 하루' })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: /예영 · 서연 · 민준 · 지우/ }).click()
  await expect(page.getByRole('heading', { name: '브라우저에서 검증한 하루' })).toBeVisible()
  await page.locator('summary').filter({ hasText: '사진으로 기억하기' }).click()
  const png = await page.evaluate(() => { const canvas = document.createElement('canvas'); canvas.width = canvas.height = 32; const c = canvas.getContext('2d')!; c.fillStyle = '#48644e'; c.fillRect(0, 0, 32, 32); return canvas.toDataURL().split(',')[1] })
  await page.getByLabel('브라우저에서 검증한 하루 사진 업로드').setInputFiles({ name: 'memory.png', mimeType: 'image/png', buffer: Buffer.from(png, 'base64') })
  await expect(page.getByText('장소 미지정', { exact: true })).toBeVisible()
  await page.getByLabel('사진의 장소').selectOption({ label: '단골 떡볶이' })
  await expect(page.getByText('직접 연결', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '대표 사진으로', exact: true }).click()
  await expect(page.getByRole('button', { name: '✓ 대표 사진' })).toBeVisible()
  await page.getByRole('button', { name: '♡ 반응' }).click()
  await expect(page.getByRole('button', { name: '♡ 반응' })).toHaveAttribute('aria-pressed', 'true')
  await page.getByLabel('브라우저에서 검증한 하루에 짧은 댓글').fill('또 만나자!')
  await page.getByRole('button', { name: '댓글 남기기' }).click()
  await expect(page.getByText('또 만나자!', { exact: false })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: /예영 · 서연 · 민준 · 지우/ }).click()
  await expect(page.getByText('또 만나자!', { exact: false })).toBeVisible()
  await page.locator('summary').filter({ hasText: '사진으로 기억하기' }).click()
  await expect(page.getByText('직접 연결', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(errors).toEqual([])
})
test('데모 9회, 전체 송금 완료 현상, 감정 추가와 9:16 PNG 다운로드', async ({ page }) => {
  test.setTimeout(90000)
  await page.goto('/')
  await page.getByRole('button', { name: '데모 데이터 불러오기', exact: true }).click()
  await expect(page.getByText('9', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '데모 데이터 불러오기', exact: true }).click()
  await expect(page.getByText('9', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: /우리의 사계절/ }).click()
  const newest = page.locator('.memory-entry').first()
  await newest.getByRole('button', { name: '지우 송금 완료', exact: true }).click()
  await expect(newest.locator('.develop-status')).toContainText('우리의 추억이 현상되었어요')
  await newest.getByLabel('올해도 너희라서 참 좋았어 감정 항목').fill('이 순간도 오래 기억해')
  await newest.getByRole('button', { name: '감정 추가' }).click()
  await expect(newest.locator('.receipt-stage')).toContainText('이 순간도 오래 기억해')
  const downloadPromise = page.waitForEvent('download')
  await newest.getByRole('button', { name: '영수증 PNG 저장' }).click()
  const download = await downloadPromise
  const stream = await download.createReadStream()
  const chunks: Buffer[] = []
  for await (const chunk of stream!) chunks.push(Buffer.from(chunk))
  const png = Buffer.concat(chunks)
  expect(png.subarray(1, 4).toString()).toBe('PNG')
  expect(png.readUInt32BE(16)).toBe(1080)
  expect(png.readUInt32BE(20)).toBe(1920)
  await page.reload()
  await page.getByRole('button', { name: /우리의 사계절/ }).click()
  await expect(page.locator('.memory-entry').first().locator('.receipt-stage')).toContainText('이 순간도 오래 기억해')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: '/tmp/receiptory-room-mobile.png', fullPage: false })
  await page.getByRole('button', { name: '기록방으로' }).click()
  await page.screenshot({ path: '/tmp/receiptory-home-mobile.png', fullPage: true })
  await page.setViewportSize({ width: 1440, height: 1100 })
  await page.screenshot({ path: '/tmp/receiptory-home-desktop.png', fullPage: true })
})
