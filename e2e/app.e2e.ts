  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.locator('.memory-entry').first().locator('.receipt-stage').screenshot({ path: '/tmp/receiptory-receipt-mobile.png' })
  await page.screenshot({ path: '/tmp/receiptory-room-mobile.png', fullPage: false })
  await page.getByRole('button', { name: '기록방으로' }).click()
  await page.screenshot({ path: '/tmp/receiptory-home-mobile.png', fullPage: true })
