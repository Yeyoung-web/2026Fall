test('QR 실제 이미지 인식, 안전한 링크 저장·새 탭, 카메라 닫기', async ({ page, context }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await context.route('https://example.com/receiptory-qr', route => route.fulfill({ body: '<h1>QR destination test fixture</h1>', contentType: 'text/html' }))
  await page.goto('/')
  await page.getByRole('button', { name: '데모 데이터 불러오기', exact: true }).click()
  await page.getByRole('button', { name: /우리의 사계절/ }).click()
  const newest = page.locator('.memory-entry').first()
  await newest.locator('summary').filter({ hasText: '네컷 붙이기' }).click()
  await newest.getByRole('button', { name: 'QR 스캔' }).click()
  const scanner = page.getByRole('dialog')
  const qr = await QRCode.toBuffer('https://example.com/receiptory-qr', { width: 400, margin: 4 })
  await scanner.getByLabel('QR 이미지로 읽기', { exact: true }).setInputFiles({ name: 'qr.png', mimeType: 'image/png', buffer: qr })
  await expect(scanner.getByLabel('읽은 QR 링크')).toHaveValue('https://example.com/receiptory-qr')
  const popupPromise = page.waitForEvent('popup')
  await scanner.getByRole('button', { name: '링크 저장하고 새 탭 열기' }).click()
  const popup = await popupPromise
  await expect(popup).toHaveURL('https://example.com/receiptory-qr')
  await popup.close()
  await expect(newest.getByRole('link', { name: 'example.com' })).toHaveAttribute('href', 'https://example.com/receiptory-qr')
  await newest.getByRole('button', { name: 'QR 스캔' }).click()
  await scanner.getByLabel('읽은 QR 링크').fill('javascript:alert(1)')
  await scanner.getByRole('button', { name: '링크 저장하고 새 탭 열기' }).click()
  await expect(scanner.getByRole('alert')).toContainText('http 또는 https')
  await context.grantPermissions(['camera'])
  await page.evaluate(() => {
    const original = navigator.mediaDevices.getUserMedia.bind(navigator.mediaDevices)
    const tracks: MediaStreamTrack[] = []
    ;(window as unknown as { testTracks: MediaStreamTrack[] }).testTracks = tracks
    navigator.mediaDevices.getUserMedia = async constraints => { const stream = await original(constraints); tracks.push(...stream.getTracks()); return stream }
  })
  await scanner.getByRole('button', { name: '카메라로 스캔' }).click()
  await expect(scanner.locator('video')).toBeVisible()
  await scanner.getByRole('button', { name: 'QR 스캐너 닫기' }).click()
  await expect.poll(() => page.evaluate(() => (window as unknown as { testTracks: MediaStreamTrack[] }).testTracks.every(track => track.readyState === 'ended'))).toBe(true)
  await page.reload()
  await page.getByRole('button', { name: /우리의 사계절/ }).click()
  await page.locator('.memory-entry').first().locator('summary').filter({ hasText: '네컷 붙이기' }).click()
  await expect(page.locator('.memory-entry').first().getByRole('link', { name: 'example.com' })).toBeVisible()
  expect(errors).toEqual([])
})
