  await page.goto('/')
  await page.getByRole('button', { name: '데모 데이터 불러오기', exact: true }).click()
  await expect(page.getByText('9', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '데모 데이터 불러오기', exact: true }).click()
  await expect(page.getByText('9', { exact: true })).toBeVisible()
