import { test, expect } from '@playwright/test'
test('390px: 만남 생성, 새로고침 복원, 사진 fallback, 반응과 댓글', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/')
  await page.getByRole('button', { name: '새로운 만남 기록하기' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('만남 이름').fill('브라우저에서 검증한 하루')
  await dialog.getByLabel('장소명').fill('단골 떡볶이')
  await dialog.getByLabel('금액 (원)').fill('40000')
  await dialog.getByRole('button', { name: '우리의 만남 기록하기' }).click()
  await expect(page.getByRole('heading', { name: '브라우저에서 검증한 하루' })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: /예영 · 서연 · 민준 · 지우/ }).click()
  await expect(page.getByRole('heading', { name: '브라우저에서 검증한 하루' })).toBeVisible()
  await page.locator('summary').filter({ hasText: '사진으로 기억하기' }).click()
  const png = await page.evaluate(() => { const canvas = document.createElement('canvas'); canvas.width = canvas.height = 32; const c = canvas.getContext('2d')!; c.fillStyle = '#48644e'; c.fillRect(0, 0, 32, 32); return canvas.toDataURL().split(',')[1] })
  await page.getByLabel('브라우저에서 검증한 하루 사진 업로드').setInputFiles({ name: 'memory.png', mimeType: 'image/png', buffer: Buffer.from(png, 'base64') })
  await expect(page.getByText('장소 미지정', { exact: true })).toBeVisible()
  await page.getByLabel('사진의 장소').selectOption({ label: '단골 떡볶이' })
  await expect(page.getByText('직접 연결', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '대표 사진으로', exact: true }).click()
  await expect(page.getByRole('button', { name: '✓ 대표 사진' })).toBeVisible()
  await page.getByRole('button', { name: '♡ 반응' }).click()
  await expect(page.getByRole('button', { name: '♡ 반응' })).toHaveAttribute('aria-pressed', 'true')
  await page.getByLabel('브라우저에서 검증한 하루에 짧은 댓글').fill('또 만나자!')
  await page.getByRole('button', { name: '댓글 남기기' }).click()
  await expect(page.getByText('또 만나자!', { exact: false })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: /예영 · 서연 · 민준 · 지우/ }).click()
  await expect(page.getByText('또 만나자!', { exact: false })).toBeVisible()
  await page.locator('summary').filter({ hasText: '사진으로 기억하기' }).click()
  await expect(page.getByText('직접 연결', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(errors).toEqual([])
})
